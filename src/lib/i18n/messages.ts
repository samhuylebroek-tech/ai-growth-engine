export const MESSAGES: Record<Locale, Dictionary> = { en, nl, fr };

export function isLocale(v: unknown): v is Locale {
  return typeof v === "string" && (LOCALES as readonly string[]).includes(v);
}

/** Picks a supported locale from a stored choice, then the browser's Accept-Language, else English. */
export function resolveLocale(
  stored: string | undefined | null,
  acceptLanguage?: string | null,
): Locale {
  if (isLocale(stored)) return stored;
  for (const part of (acceptLanguage ?? "").split(",")) {
    const base = part.trim().slice(0, 2).toLowerCase();
    if (isLocale(base)) return base;
  }
  return "en";
}

export function translate(
  locale: Locale,
  key: MessageKey | string,
  vars?: Record<string, string | number>,
): string {
  const dict = MESSAGES[locale] as Record<string, string>;
  const text = dict[key] ?? (MESSAGES.en as Record<string, string>)[key] ?? key;
  return vars
    ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
    : text;
}
